'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=html.indexOf('function displayRoutePoints(');
const end=html.indexOf('function draw()',start);
assert(start>=0&&end>start,'route display function must exist');
const context={km:(a,b)=>Math.hypot((a.lat-b.lat)*111,(a.lon-b.lon)*90)};
vm.runInNewContext(html.slice(start,end),context);
const p=(lat,lon,t,accuracy)=>({lat,lon,t,accuracy});
const switchback=[p(35,128,1000,5),p(35.0002,128,2000,5),p(35.00001,128,3000,5)];
assert.equal(context.displayRoutePoints(switchback).length,3,'high confidence out-and-back must not disappear');
const lowConfidence=[p(35,128,1000,5),p(35.0002,128,2000,40),p(35.00001,128,3000,5)];
assert.equal(context.displayRoutePoints(lowConfidence).length,2,'low confidence isolated spike can be suppressed');
assert.equal(context.displayRoutePoints(switchback.slice(0,2)).length,2,'short route remains intact');
assert(html.includes("L.polyline(routeLines,{color:'#1678d4',weight:3"),'live route uses thin line');
console.log('GPS display route switchback regression: passed');

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const begin=html.indexOf('function routeGap(');
const end=html.indexOf('function gpx(',begin);
assert(begin>=0&&end>begin,'saved route segmentation functions must exist');
const source=html.slice(begin,end);
const context={km:(a,b)=>Math.hypot((a.lat-b.lat)*111,(a.lon-b.lon)*90)};
vm.runInNewContext(source,context);
const p=(lat,lon,t,extra={})=>({lat,lon,t,...extra});
const route=context.routeSegments;
assert.equal(route([p(35,128,1000),p(35.001,128,2000)]).length,1,'continuous fixes stay together');
assert.equal(route([p(35,128,1000),p(0,0,1500),p(35.001,128,2000)]).length,2,'invalid zero fix splits route');
assert.equal(route([p(35,128,1000),p('',128,1500),p(35.001,128,2000)]).length,2,'blank latitude splits route');
assert.equal(route([p(35,128,1000),p(95,128,1500),p(35.001,128,2000)]).length,2,'out-of-range latitude splits route');
assert.equal(route([p(35,128,1000),p(35.001,128,190000)]).length,2,'long GPS outage splits route');
assert.equal(route([p(35,128,1000),p(35.001,128,2000,{breakBefore:true})]).length,2,'explicit break splits route');
assert.equal(route([p(35,128,1000),p(35.001,128,2000)]).flat().length,2,'valid fixes remain preserved');
console.log('Saved GPS route segmentation regression: passed');

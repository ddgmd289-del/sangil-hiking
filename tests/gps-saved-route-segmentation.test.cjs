'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const begin=html.indexOf('function routeGap(');
const end=html.indexOf('function gpx(',begin);
assert(begin>=0&&end>begin,'saved route segmentation functions must exist');
const source=html.slice(begin,end);
const context={km:(a,b)=>Math.hypot((a.lat-b.lat)*111,(a.lon-b.lon)*90)};
vm.runInNewContext(source,context);
const p=(lat,lon,t,extra={})=>({lat,lon,t,...extra});
const route=context.routeSegments;
assert.equal(route([p(35,128,1000),p(35.001,128,2000)]).length,1,'continuous fixes stay together');
assert.equal(route([p(35,128,1000),p(0,0,1500),p(35.001,128,2000)]).length,2,'invalid zero fix splits route');
assert.equal(route([p(35,128,1000),p('',128,1500),p(35.001,128,2000)]).length,2,'blank latitude splits route');
assert.equal(route([p(35,128,1000),p(95,128,1500),p(35.001,128,2000)]).length,2,'out-of-range latitude splits route');
assert.equal(route([p(35,128,1000),p(35.001,128,190000)]).length,2,'long GPS outage splits route');
assert.equal(route([p(35,128,1000),p(35.001,128,2000,{breakBefore:true})]).length,2,'explicit break splits route');
assert.equal(route([p(35,128,1000),p(35.001,128,2000)]).flat().length,2,'valid fixes remain preserved');
const gapPoints=[p(35,128,1000),p(35.001,128,2000),p(0,0,2500),p(35.01,128.01,3000),p(35.011,128.01,4000)];
const split=route(gapPoints);
assert.equal(split.length,2,'invalid fix separates two valid stretches');
assert.equal(split[0][0],gapPoints[0],'first route segment retains original start');
assert.equal(split[0].at(-1),gapPoints[1],'first segment retains last valid point before gap');
assert.equal(split[1][0],gapPoints[3],'second segment begins after gap');
assert.equal(split[1].at(-1),gapPoints[4],'last route segment retains original finish');
assert.equal(split.flat().length,4,'invalid fix is excluded without dropping valid fixes');
assert.equal(route([p(0,0,1000),p(35,128,2000),p(0,0,3000)]).length,1,'leading and trailing invalid fixes do not create empty segments');
assert.equal(route([p(35,128,1000),p(35.001,128,null)]).length,2,'null timestamp cannot bridge route');
assert.equal(route([p(35,128,1000),p(35.001,128,'')]).length,2,'blank timestamp cannot bridge route');
assert.equal(route([p(35,128,1000),p(35.001,128,NaN)]).length,2,'nonfinite timestamp cannot bridge route');
assert.equal(route([p(35,128,1000),p(35.001,128,0)]).length,2,'epoch zero timestamp cannot bridge route');
console.log('Saved GPS route segmentation regression: passed');

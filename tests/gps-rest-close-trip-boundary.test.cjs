const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const start=html.indexOf('function closeRest(');
const end=html.indexOf('function autoPause()',start);
assert.ok(start>=0&&end>start,'production closeRest exists');
const now=1600000;
const sandbox={Date:{now:()=>now},Number,Math,Array};
vm.runInNewContext(html.slice(start,end),sandbox,{timeout:3000});
const close=sandbox.closeRest;
const r={started:1000000,restStarted:800000,restMs:0,rests:[],pauseReason:'auto'};
close(r);
assert.equal(r.restMs,600000,'rest before trip start is clamped');
assert.equal(r.rests[0].started,1000000,'stored interval starts at trip start');
assert.equal(r.rests[0].ended,now,'stored interval ends at resume');
assert.equal(r.restStarted,null,'active rest cleared');
assert.equal(r.pauseReason,null,'pause reason cleared');
const future={started:1000000,restStarted:now+1000,restMs:5000,rests:[],pauseReason:'manual'};
close(future);
assert.equal(future.restMs,5000,'future rest does not add time');
assert.equal(future.rests.length,0,'future rest does not create interval');
const normal={started:1000000,restStarted:1400000,restMs:1000,rests:[],pauseReason:'manual'};
close(normal);
assert.equal(normal.restMs,201000,'valid manual rest duration preserved');
const invalid={started:1000000,restStarted:false,restMs:0,rests:[],pauseReason:'auto'};
close(invalid);
assert.equal(invalid.restMs,0,'boolean rest start ignored');
console.log('Rest close trip-boundary regression: PASS');
